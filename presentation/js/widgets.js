  // ------------------------------------------------------------------ easel: the same portraits, epoch after epoch
  function easel(root) {
    const frames = D.easel.frames;
    const img = root.querySelector("img"), range = root.querySelector("input"), out = root.querySelector(".readout");
    const btn = root.querySelector("button");
    range.max = frames.length - 1;
    frames.forEach((f) => { new Image().src = f.file; });
    let timer = null;
    const set = (i) => {
      const f = frames[i];
      range.value = i; img.src = f.file;
      out.innerHTML = "Époque " + f.epoch + " <small>· FID " + fr(f.fid, 1) + "</small>";
    };
    const stop = () => { clearInterval(timer); timer = null; btn.textContent = "▶ Peindre"; };
    const play = () => {
      if (Number(range.value) >= frames.length - 1) set(0);
      btn.textContent = "❚❚ Pause";
      timer = setInterval(() => {
        const i = Number(range.value) + 1;
        if (i >= frames.length) return stop();
        set(i);
      }, 420);
    };
    btn.addEventListener("click", () => (timer ? stop() : play()));
    range.addEventListener("input", () => { stop(); set(Number(range.value)); });
    const slide = slideOf(root);
    slide.addEventListener("step", (e) => { stop(); if (e.detail === 0) set(0); else if (e.detail === 1) play(); else set(frames.length - 1); });
    slide.addEventListener("leave", stop);
  }

  // ------------------------------------------------------------------ morphing between two paintings
  function morph(root) {
    const seqs = D.generated.morph;
    const imgs = Array.from(root.querySelectorAll("img[data-seq]"));
    const range = root.querySelector("input"), btn = root.querySelector("button");
    const steps = seqs[0].steps;
    range.max = steps - 1;
    seqs.forEach((s) => { for (let k = 0; k < s.steps; k++) new Image().src = s.prefix + String(k).padStart(2, "0") + ".jpg"; });
    let timer = null, dir = 1;
    const set = (k) => {
      range.value = k;
      imgs.forEach((im) => { im.src = seqs[Number(im.dataset.seq)].prefix + String(k).padStart(2, "0") + ".jpg"; });
    };
    const stop = () => { clearInterval(timer); timer = null; btn.textContent = "▶ Métamorphose"; };
    const play = () => {
      btn.textContent = "❚❚ Pause";
      timer = setInterval(() => {
        let k = Number(range.value) + dir;
        if (k >= steps - 1 || k <= 0) dir = -dir;
        set(Math.max(0, Math.min(steps - 1, k)));
      }, 170);
    };
    btn.addEventListener("click", () => (timer ? stop() : play()));
    range.addEventListener("input", () => { stop(); set(Number(range.value)); });
    const slide = slideOf(root);
    slide.addEventListener("step", (e) => { stop(); dir = 1; if (e.detail === 0) set(0); else play(); });
    slide.addEventListener("leave", stop);
  }

